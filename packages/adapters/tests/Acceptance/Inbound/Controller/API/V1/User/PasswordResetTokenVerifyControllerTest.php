<?php

declare(strict_types=1);

namespace CuriosityConference\Adapters\Tests\Acceptance\Inbound\Controller\API\V1\User;

use CuriosityConference\Adapters\Inbound\Controller\API\V1\User\PasswordResetTokenVerifyController;
use CuriosityConference\Adapters\Tests\Acceptance\AbstractWebTestCase;
use PHPUnit\Framework\Attributes\CoversNothing;
use PHPUnit\Framework\Attributes\Group;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\Uid\Uuid;

#[Group('Acceptance')]
#[CoversNothing(PasswordResetTokenVerifyController::class)]
final class PasswordResetTokenVerifyControllerTest extends AbstractWebTestCase
{
    public function testResetPasswordIsValid(): void
    {
        $payload = [
            'firstName' => 'test',
            'lastName' => 'test',
            'email' => 'test@web.de',
            'password' => 'Test123!',
            'confirmPassword' => 'Test123!',
        ];
        $this->client->request(
            'POST',
            '/api/v1/user',
            server: [
                'Content-Type' => 'application/json',
                'Accept' => 'application/json',
                'HTTP_API_KEY' => '42b1ed2a3b0cdb29b75875f3c88d454d',
            ],
            content: \json_encode($payload, \JSON_THROW_ON_ERROR),
        );
        $response = \json_decode(
            $this->client->getResponse()->getContent(),
            true,
            flags: \JSON_THROW_ON_ERROR,
        );
        $payload = [
            'email' => 'test@web.de',
        ];
        $this->client->request(
            'POST',
            '/api/v1/password/reset',
            server: [
                'Content-Type' => 'application/json',
                'Accept' => 'application/json',
                'HTTP_API_KEY' => '42b1ed2a3b0cdb29b75875f3c88d454d',
                'HTTP_AUTHORIZATION' => 'Bearer ' . $response['token'],
            ],
            content: \json_encode($payload, \JSON_THROW_ON_ERROR),
        );
        $rowUser = $this->connection->fetchAssociative(
            'SELECT * FROM user WHERE email = :email',
            ['email' => 'test@web.de'],
        );
        $rowPasswordReset = $this->connection->fetchAssociative(
            'SELECT * FROM password_reset WHERE user_id = :userId',
            ['userId' => $rowUser['id']],
        );
        $this->client->request(
            'GET',
            '/api/v1/password/reset?id=' . Uuid::fromBinary($rowUser['id'])->toRfc4122() . '&token=' . $rowPasswordReset['token'],
            server: [
                'HTTP_API_KEY' => '42b1ed2a3b0cdb29b75875f3c88d454d',
                'HTTP_AUTHORIZATION' => 'Bearer ' . $response['token'],
            ],
        );
        $response = \json_decode(
            $this->client->getResponse()->getContent(),
            true,
            flags: \JSON_THROW_ON_ERROR,
        );

        self::assertResponseStatusCodeSame(Response::HTTP_OK);
        self::assertEquals([
            'verified' => true,
        ], $response);
    }

